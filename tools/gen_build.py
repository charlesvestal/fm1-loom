"""This build's sources as a number (LOOM_BUILD, app/plat_loom.c): a hash of the app's and fm1-base's sources, so a
new build is told apart from the one that ran before it (the second core's bar, kept across an update in .noinit,
is the old build's: a new build starts with two cores again). The same sources give the same number (and image).
XY_BENCH=1 in the environment: a build with the hardware profiler (app/dsp/bench.c, tools/hw_bench.py), its own number.
  tools/gen_build.py OUT.h      (run by the build: app/fm1.toml gen)"""
import hashlib
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRS = ["app", "base/device", "base/include", "base/lib", "base/bsp/chip", "base/bsp/boards", "base/bsp/loader"]
EXT = {".c", ".h", ".S", ".ld", ".toml", ".tsv"}


def main(out):
    bench = int(os.environ.get("XY_BENCH", "0") == "1")
    h = hashlib.sha256(b"bench" if bench else b"")
    for d in DIRS:
        for f in sorted((ROOT / d).rglob("*")):
            rel = f.relative_to(ROOT)
            if f.is_file() and f.suffix in EXT and "build" not in rel.parts and "web" not in rel.parts:
                h.update(str(rel).encode() + b"\0" + f.read_bytes() + b"\0")
    v = int.from_bytes(h.digest()[:4], "little") or 1
    text = (f"/* generated by tools/gen_build.py: this build's sources */\n#pragma once\n#define LOOM_BUILD 0x{v:08X}u\n"
            f"#define XY_BENCH {bench}\n")
    p = Path(out)
    if not p.exists() or p.read_text() != text:     # (unchanged: left alone, so nothing rebuilds for it)
        p.write_text(text)


if __name__ == "__main__":
    main(sys.argv[1])
